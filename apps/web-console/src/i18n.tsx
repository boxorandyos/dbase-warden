type Lang = 'en' | 'de';

const LangContext = createContext<{
  lang: Lang;
  toggle: () => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem(LANGUAGE_KEY) === 'de' ? 'de' : 'en'));
  const value = useMemo(() => ({
    lang,
    toggle: () => {
      setLang((current) => {
        const next: Lang = current === 'en' ? 'de' : 'en';
        localStorage.setItem(LANGUAGE_KEY, next);
        return next;
      });
    },
    t: (key: string, vars?: Record<string, string | number>) => {
      const catalog = lang === 'de' ? de : en;
      let text = catalog[key] ?? en[key] ?? key;
      if (vars) {
        for (const [name, item] of Object.entries(vars)) text = text.replaceAll(`{{${name}}}`, String(item));
      }
      return text;
    },
  }), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const value = useContext(LangContext);
  if (!value) throw new Error('LanguageProvider is missing');
  return value;
}
